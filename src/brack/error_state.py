"""Management of the AUTO-BLACK-FORMATTING-ERROR file that blocks further runs.

Created when a background GitHub op fails (so the error is surfaced on the
next invocation) or when the foreground workflow aborts in a state the user
needs to investigate. Deleted by `brack --cleanup`.
"""

from __future__ import annotations

from datetime import datetime
from pathlib import Path

from . import __version__

ERROR_FILENAME = "AUTO-BLACK-FORMATTING-ERROR"
BACKGROUND_LOG_FILENAME = "background_errors.log"


def error_file_path(repo_root: Path) -> Path:
    return repo_root / ERROR_FILENAME


def background_log_path(repo_root: Path) -> Path:
    return repo_root / BACKGROUND_LOG_FILENAME


def write_error_state(repo_root: Path, error_message: str, context: str = "Unknown context") -> Path:
    path = error_file_path(repo_root)
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    path.write_text(
        _RENDER_TEMPLATE.format(
            timestamp=timestamp,
            context=context,
            error=error_message,
            version=__version__,
        )
    )
    return path


def append_background_error(repo_root: Path, process_name: str, exit_code: int, command: str) -> None:
    path = error_file_path(repo_root)
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    block = (
        "BACKGROUND PROCESS ERROR\n"
        "========================\n"
        f"Process: {process_name}\n"
        f"Timestamp: {timestamp}\n"
        f"Exit Code: {exit_code}\n"
        f"Command: {command}\n\n"
    )
    with path.open("a") as fh:
        fh.write(block)


def error_state_present(repo_root: Path) -> bool:
    return error_file_path(repo_root).exists()


def clear_error_state(repo_root: Path) -> bool:
    """Return True if an error file was present and removed."""
    path = error_file_path(repo_root)
    if not path.exists():
        return False
    path.unlink()
    bg = background_log_path(repo_root)
    if bg.exists():
        bg.unlink()
    return True


_RENDER_TEMPLATE = """BRACK TOOL ERROR STATE
======================
Timestamp: {timestamp}
Context: {context}
Error: {error}

RECOVERY INSTRUCTIONS:
1. Manually resolve the issue described above
2. Verify your git repository is in a clean state
3. Run 'brack --cleanup' to clear this error state
4. Try running brack again

Generated by: brack version {version}
"""
